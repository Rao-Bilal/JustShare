export function getFileIconComponent(filename: string, size = 20) {
  const ext = filename.split('.').pop()?.toLowerCase() || '';
  if (['png', 'jpg', 'jpeg', 'gif', 'svg', 'webp', 'bmp', 'ico', 'avif'].includes(ext)) {
    return <IconFileImage size={size} />;
  }
  if (['mp4', 'mov', 'avi', 'mkv', 'webm', 'flv'].includes(ext)) {
    return <IconFileVideo size={size} />;
  }
  if (['mp3', 'wav', 'flac', 'aac', 'ogg', 'm4a'].includes(ext)) {
    return <IconFileAudio size={size} />;
  }
  if (['zip', 'tar', 'gz', 'rar', '7z', 'bz2', 'xz'].includes(ext)) {
    return <IconFileArchive size={size} />;
  }
  if (['pdf', 'doc', 'docx', 'txt', 'rtf', 'odt', 'csv', 'xlsx', 'md'].includes(ext)) {
    return <IconFileText size={size} />;
  }
  return <IconFile size={size} />;
}

export function getDeviceTypeIconComponent(type: string, size = 20) {
  const t = (type || '').toLowerCase();
  if (t === 'phone' || t === 'mobile') return <IconSmartphone size={size} />;
  if (t === 'tablet') return <IconTablet size={size} />;
  if (t === 'desktop') return <IconMonitor size={size} />;
  return <IconLaptop size={size} />;
}
